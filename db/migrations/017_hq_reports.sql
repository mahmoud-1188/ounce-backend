-- 017_hq_reports.sql
--
-- يفعّل تقرير "الإدارة/متعدد الفروع" (HQ / multi-branch reporting).
--
-- ⚠ خلافًا لكل الميزات السابقة (015 الأصول الثابتة، 016 الرواتب) هذه ليست
-- إعادة تفعيل لسقالة ميتة بمعناها المعتاد: hq_permissions و branches.is_hq
-- موجودان في schema.sql منذ البداية، لكن لا HqTransactionsPage.js في
-- المرجع ولا أي شيء في تطبيقنا يقابلهما فعليًا يشبه ما نبنيه هنا —
-- HqTransactionsPage.js في المرجع نظام مزامنة يدوي بالكامل (تشفير رمز،
-- لصقه، إرساله واتساب) بين نسخ محلية منفصلة لا تشترك بخادم واحد، وهو ما
-- لا معنى له إطلاقًا في تطبيقنا الذي يملك قاعدة بيانات حقيقية واحدة تخدم
-- كل الفروع عبر RLS (withBranch). لذلك هذه ميزة جديدة فعليًا مبنية على
-- الجدولين الموجودين، لا نقل حرفي من المرجع.
--
-- القرار (بعد سؤال المستخدم صراحةً، إذ لا يوجد أي مستخدم اليوم يرى غير
-- فرعه في كل الباك إند):
--   1) من يرى التقرير المجمّع؟ فرع واحد فقط مُعلَّم branches.is_hq = true
--      (وليس عمود صلاحية جديد لكل مستخدم) — أي مدير (role='manager') في
--      ذلك الفرع تحديدًا يرى التقرير المجمّع لكل الفروع. تعليم فرع بأنه
--      HQ عملية تشغيلية نادرة تُجرى يدويًّا على القاعدة (update branches
--      set is_hq = true where id = '...') لا واجهة تمنحها التطبيق لأي
--      مستخدم — منح صلاحية رؤية أموال كل الفروع ليس إجراء تُفعّله شاشة.
--   2) نطاق التقرير؟ ملخصات مجمّعة فقط لكل فرع (مبيعات/مشتريات/مخزون/
--      خزنة/ذمم) بلا الدخول لتفاصيل سجلات فرع بعينه — لا صفحة "تصفّح
--      فرع" ولا كشف عمليات فردية عبر هذا المسار.
--
-- ⚠ التنفيذ يعتمد withoutBranch (db.js) عمدًا: هذا هو المسار الوحيد في
-- الكود الذي يتجاوز عزل RLS للفرع، وحمايته الوحيدة هنا هي التحقق اليدوي
-- من is_hq داخل المسار نفسه (hq.routes.js) قبل أي استعلام — إن أُزيلت تلك
-- الحراسة يرى أي مستخدم بيانات كل الفروع، لذا لا تُستخدم withoutBranch في
-- أي مسار آخر بلا نفس الحراسة الصريحة.

-- إتاحة صفحة "تقرير الفروع" في allowed_more للمدير — لا حراسة خادم إضافية
-- تلزم أبعد من requirePage("hqReports") + التحقق من is_hq نفسه في المسار،
-- تمامًا كحال fixedAssets/payroll: لا تُطبَّق تلقائيًّا على مستخدم بقائمة
-- allowed_pages مخصَّصة (custom override) — نفس التحفّظ الموثَّق سابقًا.
update roles
   set allowed_more = allowed_more || '["hqReports"]'::jsonb
 where id = 'manager'
   and not (allowed_more @> '["hqReports"]'::jsonb);
