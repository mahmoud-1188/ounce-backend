// أرقامٌ سريّة سهلة التخمين — منها الافتراضيّ المطبوع في الدليل (9999).
// من يدخل بأحدها يُطلب منه تغييره قبل العمل، ولا يُقبل رقمًا جديدًا.
const WEAK_PINS = ["0000", "1111", "1234", "1122", "2222", "9999", "4321",
  "123456", "111111", "000000", "112233"];

const isWeakPin = (pin) => WEAK_PINS.includes(String(pin || ""));

export { WEAK_PINS, isWeakPin };
